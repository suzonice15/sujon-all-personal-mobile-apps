"""
Asset generator for Game 6 — বিষয়ভিত্তিক কুইজ (Subject Quiz).

Reads   src/data/game06_quiz.json        (science questions, math objects, shapes, prompts)
        src/data/game02_seekRush.json    (Bangla number names, for math question voices)
Writes  src/assets/audio/game06/*.mp3     (question voices)
        src/assets/images/game06/pics/    (pictures not already shipped by Game 1/3)
        src/assets/images/game06/*.jpg    (crops from the design PDF)
        src/data/game06_assets.generated.js

বাংলা / ইংরেজি questions reuse Game 1 word voices; সাধারণ জ্ঞান reuses Game 3.

Usage:  python scripts/assets/generate_game06_assets.py [--force-audio]
"""
import argparse
import json
import sys

from asset_utils import (
    FLUENT_LICENSE,
    ROOT,
    crop_to,
    fluent_image,
    normalize,
    picture_key,
    save_picture,
    synth_clips,
    to_snake,
)

CONTENT = ROOT / 'src/data/game06_quiz.json'
NUMBERS = ROOT / 'src/data/game02_seekRush.json'
AUDIO_DIR = ROOT / 'src/assets/audio/game06'
IMG_DIR = ROOT / 'src/assets/images/game06'
PIC_DIR = IMG_DIR / 'pics'
OUT_JS = ROOT / 'src/data/game06_assets.generated.js'
DESIGN_PAGES = ROOT / 'pdf_pages/06 Subject Quiz'
SHARED_PIC_DIRS = [ROOT / 'src/assets/images/game01/words', ROOT / 'src/assets/images/game03/pics']

EN_PROMPTS = {'enWhichIs', 'enStartsWith', 'enNameIt'}


def audio_jobs(data, words):
    jobs = []
    for key, text in data['prompts'].items():
        jobs.append((f'p_{to_snake(key)}', text, 'en' if key in EN_PROMPTS else 'bn'))
    for li, level in enumerate(data['science']):
        for qi, (question, _, _) in enumerate(level['items']):
            jobs.append((f'sci_{li + 1}_{qi + 1}', normalize(question), 'bn'))
    for oi, (name, _) in enumerate(data['countObjects']):
        for n in range(1, 11):
            jobs.append((f'count_{oi}_{n}', f'নিচের কোনটিতে {words[n]}টি {name} আছে?', 'bn'))
    for a in range(0, 11):
        for b in range(0, 11 - a):
            jobs.append((f'add_{a}_{b}', f'{words[a]} যোগ {words[b]} সমান কত?', 'bn'))
            jobs.append((f'sub_{a + b}_{b}', f'{words[a + b]} বিয়োগ {words[b]} সমান কত?', 'bn'))
    for si, (_, _, question) in enumerate(data['shapes']):
        jobs.append((f'shape_{si}', question, 'bn'))
    return jobs


def all_pictures(data):
    pics = {e for _, e in data['countObjects']} | {s[1] for s in data['shapes']}
    for level in data['science']:
        for _, answer, decoys in level['items']:
            pics.add(answer[1])
            pics.update(d[1] for d in decoys)
    return sorted(pics)


def make_pictures(data):
    PIC_DIR.mkdir(parents=True, exist_ok=True)
    paths = {}
    for pic in all_pictures(data):
        key = picture_key(pic)
        shared = next((d for d in SHARED_PIC_DIRS if (d / f'{key}.webp').exists()), None)
        if shared:
            paths[pic] = f'../assets/images/{shared.parent.name}/{shared.name}/{key}.webp'
            continue
        out = PIC_DIR / f'{key}.webp'
        if not out.exists():
            save_picture(fluent_image(pic), out)
        paths[pic] = f'../assets/images/game06/pics/{key}.webp'
    (PIC_DIR / 'LICENSE-fluentui-emoji.txt').write_text(FLUENT_LICENSE, encoding='utf-8')
    return paths


def make_design_images():
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    crop_to(DESIGN_PAGES / 'page_1.png', (480, 10, 1500, 660), 900, IMG_DIR / 'title_hero.jpg')
    page = DESIGN_PAGES / 'page_2.png'
    # Page 6 shows the বাংলা card without the design's mouse pointer.
    crop_to(DESIGN_PAGES / 'page_6.png', (500, 392, 828, 628), 300, IMG_DIR / 'subject_bn.jpg')
    crop_to(page, (855, 392, 1175, 628), 300, IMG_DIR / 'subject_en.jpg')
    crop_to(page, (1203, 392, 1535, 628), 300, IMG_DIR / 'subject_math.jpg')
    crop_to(page, (597, 662, 985, 908), 300, IMG_DIR / 'subject_science.jpg')
    crop_to(page, (1019, 662, 1450, 908), 300, IMG_DIR / 'subject_gk.jpg')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--force-audio', action='store_true')
    args = parser.parse_args()

    data = json.loads(CONTENT.read_text(encoding='utf-8'))
    words = json.loads(NUMBERS.read_text(encoding='utf-8'))['numberWords']
    jobs = audio_jobs(data, words)
    synth_clips(jobs, AUDIO_DIR, args.force_audio)
    pictures = make_pictures(data)
    make_design_images()

    lines = [
        '// AUTO-GENERATED by scripts/assets/generate_game06_assets.py — do not edit by hand.',
        '/* eslint-disable */',
        '',
        'export const AUDIO = {',
        *[f"  {key}: require('../assets/audio/game06/{key}.mp3')," for key, _, _ in jobs],
        '};',
        '',
        '// Keyed by the picture code used in game06_quiz.json.',
        'export const PICTURES = {',
        *[f"  {json.dumps(pic, ensure_ascii=False)}: require('{path}')," for pic, path in pictures.items()],
        '};',
        '',
    ]
    OUT_JS.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Done: {len(jobs)} clips, {len(pictures)} pictures.')


if __name__ == '__main__':
    sys.exit(main())
