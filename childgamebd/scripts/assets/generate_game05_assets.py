"""
Asset generator for Game 5 — ব্লক ফিল (Block Fill, a picture crossword).

Writes  src/assets/audio/game05/*.mp3          (spoken prompts)
        src/assets/images/game05/*.jpg         (crops from the design PDF)
        src/assets/images/common/*.webp        (math clue pictures)
        src/data/game05_assets.generated.js    (static require() map)

Words, pictures and voices come from Game 3 (বাংলা/English) and Game 2 (number names).

Usage:  python scripts/assets/generate_game05_assets.py [--force-audio]
"""
import argparse
import sys

from asset_utils import FLUENT_NAMES, ROOT, crop_to, make_ui_pictures, synth_clips

AUDIO_DIR = ROOT / 'src/assets/audio/game05'
IMG_DIR = ROOT / 'src/assets/images/game05'
OUT_JS = ROOT / 'src/data/game05_assets.generated.js'
DESIGN_PAGES = ROOT / 'pdf_pages/05 Block fill'

PROMPTS = {
    'p_instruction': 'ছবি আর ইশারা দেখে শব্দ বসিয়ে ঘরগুলো পূরণ করো!',
    'p_wrong_word': 'কোনো একটা অক্ষর ভুল হয়েছে। আবার চেষ্টা করো!',
    'p_level_done': 'অভিনন্দন! তুমি লেভেলটি সম্পূর্ণ করেছো!',
}

FLUENT_NAMES.update({'➕': 'Plus', '➖': 'Minus', '\U0001f9ee': 'Abacus', '\U0001f4c5': 'Calendar'})
UI_PICTURES = {'math_plus': '➕', 'math_minus': '➖', 'math_abacus': '\U0001f9ee', 'calendar': '\U0001f4c5'}


def make_images():
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    crop_to(DESIGN_PAGES / 'page_1.png', (505, 80, 1515, 725), 900, IMG_DIR / 'title_hero.jpg')
    page = DESIGN_PAGES / 'page_2.png'
    crop_to(page, (490, 470, 805, 720), 300, IMG_DIR / 'subject_bn.jpg')
    crop_to(page, (920, 470, 1235, 720), 300, IMG_DIR / 'subject_math.jpg')
    crop_to(page, (1355, 470, 1670, 720), 300, IMG_DIR / 'subject_en.jpg')
    make_ui_pictures(UI_PICTURES)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--force-audio', action='store_true')
    args = parser.parse_args()

    synth_clips([(key, text, 'bn') for key, text in PROMPTS.items()], AUDIO_DIR, args.force_audio)
    make_images()
    lines = [
        '// AUTO-GENERATED by scripts/assets/generate_game05_assets.py — do not edit by hand.',
        '/* eslint-disable */',
        '',
        'export const AUDIO = {',
        *[f"  {key}: require('../assets/audio/game05/{key}.mp3')," for key in PROMPTS],
        '};',
        '',
        'export const PROMPT_TEXT = {',
        *[f"  {key}: '{text}'," for key, text in PROMPTS.items()],
        '};',
        '',
    ]
    OUT_JS.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Done: {len(PROMPTS)} prompts.')


if __name__ == '__main__':
    sys.exit(main())
