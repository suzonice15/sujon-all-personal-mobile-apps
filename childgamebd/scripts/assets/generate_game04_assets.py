"""
Asset generator for Game 4 — Word Search (শব্দ খোঁজার অভিযান).

Writes  src/assets/audio/game04/*.mp3          (spoken prompts)
        src/assets/images/game04/*.jpg         (crops from the design PDF)
        src/data/game04_assets.generated.js    (static require() map)

The words, pictures and word voices come from Game 1, so only prompts are generated here.

Usage:  python scripts/assets/generate_game04_assets.py [--force-audio]
"""
import argparse
import sys

from asset_utils import ROOT, crop_to, synth_clips

AUDIO_DIR = ROOT / 'src/assets/audio/game04'
IMG_DIR = ROOT / 'src/assets/images/game04'
OUT_JS = ROOT / 'src/data/game04_assets.generated.js'
DESIGN_PAGES = ROOT / 'pdf_pages/04 Word Search'

PROMPTS = {
    'p_choose_language': 'কোন ভাষায় শব্দ খুঁজতে চাও?',
    'p_find_words': 'নিচের শব্দগুলো খুঁজে বের করো! আঙুল দিয়ে অক্ষরের ওপর টেনে শব্দটি দাগাও।',
    'p_all_found': 'অভিনন্দন! তুমি সব শব্দ খুঁজে পেয়েছো!',
    'p_time_up': 'সময় শেষ! আবার চেষ্টা করো, তুমি পারবে!',
    'p_not_a_word': 'এটা তালিকার কোনো শব্দ নয়। আবার দেখো!',
}


def make_images():
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    crop_to(DESIGN_PAGES / 'page_1.png', (465, 60, 1460, 322), 900, IMG_DIR / 'title_hero.jpg')
    page = DESIGN_PAGES / 'page_2.png'
    crop_to(page, (545, 450, 965, 760), 360, IMG_DIR / 'lang_bn.jpg')
    crop_to(page, (1030, 450, 1450, 760), 360, IMG_DIR / 'lang_en.jpg')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--force-audio', action='store_true')
    args = parser.parse_args()

    synth_clips([(key, text, 'bn') for key, text in PROMPTS.items()], AUDIO_DIR, args.force_audio)
    make_images()
    lines = [
        '// AUTO-GENERATED by scripts/assets/generate_game04_assets.py — do not edit by hand.',
        '/* eslint-disable */',
        '',
        'export const AUDIO = {',
        *[f"  {key}: require('../assets/audio/game04/{key}.mp3')," for key in PROMPTS],
        '};',
        '',
        'export const PROMPT_TEXT = {',
        *[f"  {key}: '{text}'," for key, text in PROMPTS.items()],
        '};',
        '',
    ]
    OUT_JS.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Done: {len(PROMPTS)} prompts.')


if __name__ == '__main__':
    sys.exit(main())
