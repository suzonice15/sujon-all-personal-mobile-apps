"""
Asset generator for Game 2 — বর্ণ ও সংখ্যা খোঁজার অভিযান (Word Seek Rush).

Reads   src/data/game02_seekRush.json           (number names + prompts)
Writes  src/assets/audio/game02/*.mp3            (Bangla number names 0-99 + prompts)
        src/assets/images/game02/*.jpg           (crops from the design PDF / cover)
        src/assets/images/common/*.webp          (shared UI pictures)
        src/data/game02_assets.generated.js      (static require() map)

Letters and words reuse Game 1's voice clips and pictures.

Usage:  python scripts/assets/generate_game02_assets.py [--force-audio]
"""
import argparse
import json
import sys

from asset_utils import ROOT, crop_to, make_ui_pictures, normalize, synth_clips, to_snake

CONTENT = ROOT / 'src/data/game02_seekRush.json'
AUDIO_DIR = ROOT / 'src/assets/audio/game02'
IMG_DIR = ROOT / 'src/assets/images/game02'
OUT_JS = ROOT / 'src/data/game02_assets.generated.js'
COVER = ROOT / 'src/assets/games/game_02.jpg'
DESIGN_PAGES = ROOT / 'pdf_pages/02 Word Seek Rush'

UI_PICTURES = {
    'magnifier': '\U0001f50d', 'glowing_star': '\U0001f31f', 'check_mark': '✅',
    'cross_mark': '❌', 'alarm_clock': '⏰',
}


def audio_jobs(data):
    jobs = [(f'n{n}', normalize(word), 'bn') for n, word in enumerate(data['numberWords'])]
    jobs += [(f'p_{to_snake(key)}', text, 'bn') for key, text in data['prompts'].items()]
    return jobs


def make_images():
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    crop_to(COVER, (480, 95, 1300, 615), 900, IMG_DIR / 'title_hero.jpg')
    page = DESIGN_PAGES / 'page_2.png'
    crop_to(page, (185, 235, 685, 668), 380, IMG_DIR / 'subject_bangla.jpg')
    crop_to(page, (722, 215, 1222, 668), 380, IMG_DIR / 'subject_math.jpg')
    crop_to(page, (1255, 235, 1755, 668), 380, IMG_DIR / 'subject_english.jpg')
    make_ui_pictures(UI_PICTURES)


def write_js(jobs):
    lines = [
        '// AUTO-GENERATED by scripts/assets/generate_game02_assets.py — do not edit by hand.',
        '/* eslint-disable */',
        '',
        'export const AUDIO = {',
    ]
    lines += [f"  {key}: require('../assets/audio/game02/{key}.mp3')," for key, _, _ in jobs]
    lines += ['};', '']
    OUT_JS.write_text('\n'.join(lines), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--force-audio', action='store_true')
    args = parser.parse_args()

    data = json.loads(CONTENT.read_text(encoding='utf-8'))
    jobs = audio_jobs(data)
    synth_clips(jobs, AUDIO_DIR, args.force_audio)
    make_images()
    write_js(jobs)
    print(f'Done: {len(jobs)} clips.')


if __name__ == '__main__':
    sys.exit(main())
